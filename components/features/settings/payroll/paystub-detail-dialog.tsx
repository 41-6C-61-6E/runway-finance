'use client';

import React from 'react';
import { Dialog, DialogContent, DialogHeader, DialogTitle, DialogDescription, DialogFooter } from '@/components/ui/dialog';
import { Input } from '@/components/ui/input';
import { formatCurrency } from '@/lib/utils/format';
import type { Paystub, PaystubLineItem } from './types';
import { formatDate, sectionLabel } from './utils';

export type ViewingPaystub = Paystub & {
  lineItems?: Array<PaystubLineItem & { amount?: string; mappingAction?: string; categoryId?: string | null }>;
  sourceJson?: string | null;
};

interface PaystubDetailDialogProps {
  viewingPaystub: ViewingPaystub | null;
  onClose: () => void;
  editingPaystub: boolean;
  editLineItems: { id: string; amount: string }[];
  editSaving: boolean;
  getCategoryName: (id: string) => string;
  handleEditLineItemAmount: (id: string, amount: string) => void;
  handleStartEdit: () => void;
  handleCancelEdit: () => void;
  handleSaveEdit: () => void;
  handleDownloadPaystubJson: (paystub: ViewingPaystub) => void;
}

export function PaystubDetailDialog({
  viewingPaystub,
  onClose,
  editingPaystub,
  editLineItems,
  editSaving,
  getCategoryName,
  handleEditLineItemAmount,
  handleStartEdit,
  handleCancelEdit,
  handleSaveEdit,
  handleDownloadPaystubJson,
}: PaystubDetailDialogProps) {
  return (
    <Dialog
      open={!!viewingPaystub}
      onOpenChange={(open) => {
        if (!open) {
          onClose();
        }
      }}
    >
      <DialogContent className="max-w-lg max-h-[80vh] overflow-y-auto">
        <DialogHeader>
          <DialogTitle>Paystub Details</DialogTitle>
          <DialogDescription>
            {viewingPaystub && (
              <>
                {formatDate(viewingPaystub.checkDate)}
                {viewingPaystub.employerName && ` · ${viewingPaystub.employerName}`}
                {viewingPaystub.isAutoGenerated && ' · Auto-generated'}
              </>
            )}
          </DialogDescription>
        </DialogHeader>

        {viewingPaystub && (
          <div className="space-y-4">
            {/* Summary */}
            <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
              <div className="p-3 bg-muted/50 rounded-lg">
                <div className="text-xs text-muted-foreground">Gross</div>
                <div className="text-sm font-medium text-foreground blur-number">{formatCurrency(viewingPaystub.grossCurrent)}</div>
              </div>
              <div className="p-3 bg-muted/50 rounded-lg">
                <div className="text-xs text-muted-foreground">Net</div>
                <div className="text-sm font-medium text-foreground blur-number">{formatCurrency(viewingPaystub.netCurrent)}</div>
              </div>
              <div className="p-3 bg-muted/50 rounded-lg">
                <div className="text-xs text-muted-foreground">Taxes</div>
                <div className="text-sm font-medium text-foreground blur-number">{formatCurrency(viewingPaystub.taxesCurrent)}</div>
              </div>
              <div className="p-3 bg-muted/50 rounded-lg">
                <div className="text-xs text-muted-foreground">Deductions</div>
                <div className="text-sm font-medium text-foreground blur-number">{formatCurrency(viewingPaystub.deductionsCurrent)}</div>
              </div>
            </div>

            <div className="text-xs text-muted-foreground">
              Pay Period: {formatDate(viewingPaystub.payPeriodStart)} — {formatDate(viewingPaystub.payPeriodEnd)}
            </div>

            {/* Line Items */}
            {viewingPaystub.lineItems && viewingPaystub.lineItems.length > 0 && (
              <div className="space-y-3">
                {['earnings', 'taxes', 'before_tax_deductions', 'after_tax_deductions'].map((section) => {
                  const items = viewingPaystub.lineItems?.filter((li) => li.section === section) || [];
                  if (items.length === 0) return null;
                  return (
                    <div key={section}>
                      <h4 className="text-xs font-semibold text-muted-foreground uppercase tracking-wide mb-1">
                        {sectionLabel(`${section}:`)}
                      </h4>
                      <div className="space-y-0.5">
                        {items.map((li) => {
                          const editItem = editingPaystub ? editLineItems.find((e) => e.id === li.id) : null;
                          return (
                            <div key={li.id} className="flex items-center justify-between py-1 px-2 bg-muted/40 rounded">
                              <div className="flex items-center gap-2 min-w-0">
                                <span className={`w-1.5 h-1.5 rounded-full flex-shrink-0 ${
                                  li.mappingAction === 'import' ? 'bg-chart-1' : 'bg-muted-foreground/30'
                                }`} />
                                <span className="text-xs text-foreground truncate">{li.description}</span>
                                {li.mappingAction === 'import' && li.categoryId && (
                                  <span className="text-[10px] text-primary/70 flex-shrink-0">→ {getCategoryName(li.categoryId)}</span>
                                )}
                              </div>
                              {editingPaystub && editItem ? (
                                <div className="flex items-center gap-1">
                                  <span className="text-[10px] text-muted-foreground">$</span>
                                  <Input
                                    type="number"
                                    step="0.01"
                                    value={editItem.amount}
                                    onChange={(e) => handleEditLineItemAmount(li.id, e.target.value)}
                                    className="w-24 text-xs h-7"
                                  />
                                </div>
                              ) : (
                                <span className="text-xs font-mono text-foreground blur-number flex-shrink-0">
                                  {formatCurrency(li.amount || li.currentAmount)}
                                </span>
                              )}
                            </div>
                          );
                        })}
                      </div>
                    </div>
                  );
                })}
              </div>
            )}
          </div>
        )}

        <DialogFooter>
          {editingPaystub ? (
            <>
              <button
                type="button"
                onClick={handleCancelEdit}
                className="px-4 py-2 text-sm text-foreground bg-muted hover:bg-accent rounded-lg transition-colors"
              >
                Cancel
              </button>
              <button
                type="button"
                onClick={handleSaveEdit}
                disabled={editSaving}
                className="px-4 py-2 text-sm font-semibold text-primary-foreground bg-primary rounded-lg hover:opacity-90 disabled:opacity-50 transition-all"
              >
                {editSaving ? 'Saving...' : 'Save'}
              </button>
            </>
          ) : (
            <>
              {viewingPaystub?.source === 'json' && viewingPaystub?.sourceJson && (
                <button
                  type="button"
                  onClick={() => handleDownloadPaystubJson(viewingPaystub)}
                  className="px-4 py-2 text-sm font-medium text-foreground border border-border hover:bg-muted rounded-lg transition-colors inline-flex items-center gap-1"
                >
                  📥 Download Original JSON
                </button>
              )}
              <button
                type="button"
                onClick={handleStartEdit}
                className="px-4 py-2 text-sm font-medium text-foreground border border-border hover:bg-muted rounded-lg transition-colors"
              >
                Edit
              </button>
              <button
                type="button"
                onClick={onClose}
                className="px-4 py-2 text-sm text-foreground bg-muted hover:bg-accent rounded-lg transition-colors"
              >
                Close
              </button>
            </>
          )}
        </DialogFooter>
      </DialogContent>
    </Dialog>
  );
}
